# ===========================================================================
# pet_design_export.py - publish the editable text-only pet design
#
# Edit docs/pet-expansion/pet-design.json, then run this tool. No workbook needed.
# ===========================================================================
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]


# ================
# main
# ================
def main():
 design = json.loads((ROOT / "docs/pet-expansion/pet-design.json").read_text(encoding="utf-8"))
 for key in ("rules", "pets", "skills", "treeSkills", "gear", "affixes", "procs"):
  if key not in design:
   raise ValueError("Missing section: " + key)
 for key in ("skills", "treeSkills", "affixes"):
  ids = [row["id"] for row in design[key]]
  if len(ids) != len(set(ids)):
   raise ValueError("Duplicate IDs in " + key)
 if len(design["gear"]) != 9 or len(design["treeSkills"]) != 60:
  raise ValueError("Expected nine degrees and sixty skill books")
 text = json.dumps(design, ensure_ascii=False, indent="\t") + "\n"
 for path in ("apps/server/internal/game/companion/petdesign.json", "scripts/build/shared/pet-design.json"):
  (ROOT / path).write_text(text, encoding="utf-8", newline="\n")
 module = "// Generated by scripts/tools/pet_design_export.py from docs/pet-expansion/pet-design.json - do not edit.\n"
 (ROOT / "apps/client-next/src/engine/foundation/ui/pet-design-data.ts").write_text(module + "export const PET_DESIGN = " + text.rstrip() + " as const;\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
 main()
